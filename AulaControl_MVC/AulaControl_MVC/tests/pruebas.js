// Pruebas automatizadas de reglas de negocio. Ejecutar con: node tests/pruebas.js
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const store=new Map();
const localStorage={getItem:key=>store.has(key)?store.get(key):null,setItem:(key,value)=>store.set(key,String(value))};
const globalObject={localStorage,console,Date,Math,crypto:require('node:crypto').webcrypto};
globalObject.window=globalObject;
const context=vm.createContext(globalObject);
const scripts=['js/data/demoStudents.js','js/models/Student.js','js/models/AttendanceRecord.js','js/services/LocalStorageRepository.js','js/services/AttendanceService.js'];
for(const file of scripts)vm.runInContext(fs.readFileSync(path.join(__dirname,'..',file),'utf8'),context,{filename:file});
const {AulaControl:AC}=context.window;
const service=new AC.AttendanceService(new AC.LocalStorageRepository());
assert.equal(service.students.length,12,'Debe haber 12 estudiantes iniciales');
const student=service.students[0];
assert.throws(()=>service.saveStudent({codigo:student.codigo,nombres:'Prueba',apellidos:'Test',documento:'DOCUMENTO_NUEVO',correo:'prueba@example.com',curso:'Pruebas'}),/código/);
assert.throws(()=>service.saveStudent({codigo:'COD-NUEVO',nombres:'Prueba',apellidos:'Test',documento:student.documento,correo:'prueba@example.com',curso:'Pruebas'}),/documento/);
for(const fecha of ['2026-11-01','2026-11-02','2026-11-03'])service.mark(student.id,fecha,'Falla');
assert.equal(service.count(student.id,'Falla'),3);
service.mark(student.id,'2026-11-01','Asistencia');
assert.equal(service.count(student.id,'Falla'),2,'Corregir fecha no debe duplicar registro');
assert.equal(service.records.filter(x=>x.estudianteId===student.id).length,3);
assert.equal(service.filteredHistory({estado:'Falla'}).length,2);
const saved=new AC.AttendanceService(new AC.LocalStorageRepository());
assert.equal(saved.students.length,12,'Persistencia estudiantes');
assert.equal(saved.records.length,3,'Persistencia registros');
saved.deleteStudent(student.id);
assert.equal(saved.records.length,0,'Eliminar estudiante elimina su historial');
assert.equal(saved.students.length,11);
console.log('OK: estudiantes iniciales, duplicados, 3 fallas, corrección, filtros, persistencia y eliminación en cascada.');
